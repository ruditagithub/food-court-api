/**
 * Intelligent image resolver based on dish name, theme genre, and beverage status
 */
export function resolveMenuImageUrl(menuName: string, genre: string, isDrink?: boolean, seedIndex = 0): string {
  const lowerName = menuName.toLowerCase()
  const lowerGenre = genre.toLowerCase()

  const pick = (list: string[]) => list[Math.abs(seedIndex) % list.length]

  if (isDrink) {
    if (lowerName.includes('kopi') || lowerName.includes('coffee') || lowerName.includes('latte') || lowerName.includes('espresso') || lowerName.includes('cappuccino')) {
      return pick(dishCollections.coffee)
    }
    if (lowerName.includes('boba') || lowerName.includes('pearl') || lowerName.includes('milk tea') || lowerName.includes('matcha')) {
      return pick(dishCollections.boba)
    }
    if (lowerName.includes('jus') || lowerName.includes('juice') || lowerName.includes('smoothie') || lowerName.includes('alpukat') || lowerName.includes('mangga') || lowerName.includes('jeruk')) {
      return pick(dishCollections.juice)
    }
    return pick(dishCollections.tea)
  }

  // Specific Food Checks
  if (lowerName.includes('rawon') || lowerGenre.includes('rawon')) {
    return pick(dishCollections.rawon)
  }
  if (lowerName.includes('sate') || lowerGenre.includes('sate')) {
    return pick(dishCollections.sate)
  }
  if (lowerName.includes('rendang') || lowerGenre.includes('padang')) {
    return pick(dishCollections.rendang)
  }
  if (lowerName.includes('soto')) {
    return pick(dishCollections.soto)
  }
  if (lowerName.includes('bakso')) {
    return pick(dishCollections.bakso)
  }
  if (lowerName.includes('sei') || lowerGenre.includes('sei')) {
    return pick(dishCollections.sei)
  }
  if (lowerName.includes('bebek')) {
    return pick(dishCollections.duck)
  }
  if (lowerName.includes('ayam') || lowerName.includes('geprek') || lowerName.includes('chicken') || lowerName.includes('katsu')) {
    return pick(dishCollections.chicken)
  }
  if (lowerName.includes('nasi goreng') || lowerName.includes('fried rice')) {
    return pick(dishCollections.nasiGoreng)
  }
  if (lowerName.includes('kwetiau') || lowerName.includes('mie') || lowerName.includes('bihun') || lowerName.includes('noodle')) {
    return pick(dishCollections.noodles)
  }
  if (lowerName.includes('ramen')) {
    return pick(dishCollections.ramen)
  }
  if (lowerName.includes('sushi') || lowerName.includes('sashimi') || lowerName.includes('maki')) {
    return pick(dishCollections.sushi)
  }
  if (lowerName.includes('dimsum') || lowerName.includes('siomay') || lowerName.includes('hakau') || lowerName.includes('dumpling')) {
    return pick(dishCollections.dimsum)
  }
  if (lowerName.includes('burger')) {
    return pick(dishCollections.burger)
  }
  if (lowerName.includes('pizza')) {
    return pick(dishCollections.pizza)
  }
  if (lowerName.includes('pasta') || lowerName.includes('spaghetti') || lowerName.includes('carbonara')) {
    return pick(dishCollections.pasta)
  }
  if (lowerName.includes('steak') || lowerName.includes('wagyu') || lowerName.includes('ribeye')) {
    return pick(dishCollections.steak)
  }
  if (lowerName.includes('croissant') || lowerName.includes('pastry') || lowerName.includes('toast') || lowerName.includes('bakery')) {
    return pick(dishCollections.croissant)
  }
  if (lowerName.includes('martabak')) {
    return pick(dishCollections.martabak)
  }
  if (lowerName.includes('salad') || lowerName.includes('bowl') || lowerName.includes('healthy')) {
    return pick(dishCollections.healthyBowl)
  }
  if (lowerName.includes('cake') || lowerName.includes('waffle') || lowerName.includes('pancake') || lowerName.includes('ice cream') || lowerName.includes('gelato') || lowerName.includes('dessert')) {
    return pick(dishCollections.dessert)
  }

  // Genre fallbacks
  if (lowerGenre.includes('asian') || lowerGenre.includes('chinese') || lowerGenre.includes('japanese')) {
    return pick(dishCollections.ramen)
  }
  if (lowerGenre.includes('western') || lowerGenre.includes('brunch')) {
    return pick(dishCollections.burger)
  }

  return pick(dishCollections.nasiGoreng)
}

